-- Một dòng là một SKU/đơn vị bán trong một đơn; tách dòng để báo cáo không phải bóc JSON.
CREATE TABLE `hicrm_shop_order_items` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'Khóa chính tăng tự động.',
  `order_id` BIGINT UNSIGNED NOT NULL COMMENT 'ID hicrm_shop_orders.',
  `line_no` SMALLINT UNSIGNED NOT NULL COMMENT 'Số thứ tự dòng trong đơn, bắt đầu 1.',
  `product_id` BIGINT NOT NULL COMMENT 'ID hicrm_products; biến thể độc lập có ID riêng.',
  `product_code` VARCHAR(50) NOT NULL COMMENT 'Mã SKU chụp lúc đặt.',
  `product_name` VARCHAR(255) NOT NULL COMMENT 'Tên chụp, không đổi theo tên sản phẩm hiện tại.',
  `unit_id` INT NOT NULL COMMENT 'ID đơn vị bán hicrm_units.',
  `unit_name` VARCHAR(50) NOT NULL COMMENT 'Tên đơn vị chụp: hộp, chai, viên.',
  `quantity` DECIMAL(14,3) NOT NULL COMMENT 'Lượng bán; chỉ cho số lẻ khi sản phẩm cho phép.',
  `base_quantity` DECIMAL(14,3) NOT NULL COMMENT 'Lượng quy về SKU cơ sở để giữ/xuất kho.',
  `unit_price` DECIMAL(18,2) NOT NULL COMMENT 'Giá một đơn vị trước giảm, giả định đã gồm thuế.',
  `promotion_id` BIGINT NULL COMMENT 'ID chương trình chính hicrm_promotions.',
  `promotion_discount` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Tổng giảm khuyến mãi trên dòng.',
  `line_amount` DECIMAL(18,2) NOT NULL COMMENT 'ROUND(quantity * unit_price,2) - promotion_discount, trước voucher/điểm.',
  `allocated_discount` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Phân bổ voucher/điểm, phục vụ tính hoàn/doanh thu.',
  `tax_amount` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Thuế đã nằm trong line_amount, không cộng lại.',
  `cost_amount` DECIMAL(18,2) NULL COMMENT 'Tổng giá vốn đã xuất; NULL khi chưa có dữ liệu.',
  `product_snapshot` JSON NULL COMMENT 'Thông số, biến thể, quy đổi đơn vị, ảnh và các khuyến mãi đã áp dụng.',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo, giờ Việt Nam.',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật gần nhất.',
  PRIMARY KEY (id),
  UNIQUE KEY uq_shop_line (order_id,line_no),
  KEY ix_shop_item_product (product_id,order_id),
  CONSTRAINT ck_shop_order_items CHECK (quantity>0 AND base_quantity>0 AND unit_price>=0 AND promotion_discount>=0 AND line_amount=ROUND(quantity*unit_price,2)-promotion_discount AND line_amount>=0 AND allocated_discount>=0 AND allocated_discount<=line_amount AND tax_amount>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

