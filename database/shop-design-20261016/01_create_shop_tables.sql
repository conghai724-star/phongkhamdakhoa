  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'Khóa chính tăng tự động.',
  `product_id` BIGINT NOT NULL COMMENT 'SKU cơ sở hicrm_products.id.',
  `warehouse_id` INT NOT NULL COMMENT 'Kho hicrm_warehouses.id.',
  `lot_code` VARCHAR(80) NOT NULL COMMENT 'Mã lô; cùng SKU/kho/lô chỉ có một hạn dùng.',
  `expires_on` DATE NULL COMMENT 'Hạn dùng; NULL chỉ khi hàng không bắt buộc theo hạn.',
  `quantity_on_hand` DECIMAL(14,3) NOT NULL DEFAULT 0 COMMENT 'Tồn vật lý theo đơn vị cơ sở.',
  `quantity_reserved` DECIMAL(14,3) NOT NULL DEFAULT 0 COMMENT 'Tồn giữ chưa xuất.',
  `unit_cost` DECIMAL(18,2) NULL COMMENT 'Giá vốn một đơn vị cơ sở, NULL nếu chưa biết.',
  `status` ENUM('active','quarantine','blocked') NOT NULL DEFAULT 'active' COMMENT 'Chỉ active còn hạn mới bán; hàng trả có thể quarantine.',
  `source_ref` VARCHAR(100) NULL COMMENT 'Định danh lô phần mềm kho ngoài nếu có.',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo, giờ Việt Nam.',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật gần nhất.',
  PRIMARY KEY (id),
  UNIQUE KEY uq_stock_lot (product_id,warehouse_id,lot_code),
  KEY ix_stock_fefo (product_id,warehouse_id,status,expires_on,id),
  KEY ix_stock_expiry (status,expires_on,id),
  CONSTRAINT ck_stock_lots CHECK (quantity_on_hand>=0 AND quantity_reserved>=0 AND quantity_reserved<=quantity_on_hand AND (unit_cost IS NULL OR unit_cost>=0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

