-- Một dòng là một đơn bán hàng online, kể cả khách chưa đăng ký.
CREATE TABLE `hicrm_shop_orders` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'Khóa chính tăng tự động.',
  `order_code` VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Mã đơn công khai duy nhất.',
  `checkout_key` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'SHA-256 khóa gửi đơn, chống tạo lặp khi retry/double-click.',
  `legacy_booking_id` INT UNSIGNED NULL COMMENT 'ID booking_internal khi chuyển dữ liệu cũ, NULL cho đơn mới.',
  `user_id` BIGINT NULL COMMENT 'ID hicrm_users; NULL là khách vãng lai.',
  `warehouse_id` INT NOT NULL COMMENT 'ID kho/điểm nhận hicrm_warehouses.',
  `recipient_name` VARCHAR(150) NOT NULL COMMENT 'Tên người nhận chụp lúc đặt.',
  `recipient_phone` VARCHAR(20) CHARACTER SET ascii NOT NULL COMMENT 'SĐT chuẩn hóa chụp lúc đặt, không đổi theo hồ sơ.',
  `recipient_email` VARCHAR(254) NULL COMMENT 'Email nếu có.',
  `delivery_method` ENUM('pickup','delivery') NOT NULL COMMENT 'Nhận tại nhà thuốc hoặc giao tận nơi.',
  `address_snapshot` JSON NULL COMMENT 'address_line, province_code/name, ward_code/name; delivery bắt buộc có địa chỉ.',
  `delivery_status` ENUM('not_started','preparing','in_transit','delivered','failed','returned') NOT NULL DEFAULT 'not_started' COMMENT 'Trạng thái giao nhận, độc lập trạng thái đơn và tiền.',
  `carrier` VARCHAR(80) NULL COMMENT 'Đơn vị giao hàng.',
  `tracking_code` VARCHAR(100) NULL COMMENT 'Mã vận đơn.',
  `status` ENUM('pending','confirmed','preparing','shipping','completed','cancelled','rejected') NOT NULL DEFAULT 'pending' COMMENT 'Trạng thái xử lý đơn.',
  `payment_status` ENUM('unpaid','partial','paid','partial_refund','refunded') NOT NULL DEFAULT 'unpaid' COMMENT 'Trạng thái tiền tổng hợp từ khoản thu/hoàn thành công.',
  `payment_method` ENUM('momo','vnpay','zalopay','bank','cod','cash') NOT NULL COMMENT 'Lựa chọn lúc đặt, không đồng nghĩa đã thu tiền.',
  `subtotal` DECIMAL(18,2) NOT NULL COMMENT 'Tổng line_amount sau khuyến mãi sản phẩm, trước voucher/điểm; giả định giá đã gồm VAT.',
  `shipping_fee` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Phí giao sau ưu đãi vận chuyển, không âm.',
  `voucher_id` BIGINT UNSIGNED NULL COMMENT 'ID hicrm_vouchers.',
  `voucher_code` VARCHAR(50) NULL COMMENT 'Mã voucher chụp lúc đặt.',
  `voucher_discount` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Tiền giảm voucher, không tính lặp vào giảm giá dòng.',
  `points_used` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Số điểm giữ/đổi, không phải tiền.',
  `points_discount` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Tiền quy đổi điểm theo tỷ lệ snapshot.',
  `total_amount` DECIMAL(18,2) NOT NULL COMMENT 'subtotal + shipping_fee - voucher_discount - points_discount.',
  `paid_amount` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Tổng khách đã trả, gồm COD đã thu; không cộng lại khi hãng chuyển tiền về.',
  `refunded_amount` DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT 'Tiền đã hoàn thành công, không tính yêu cầu chưa xong.',
  `points_expected` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Điểm dự kiến trang cảm ơn, chưa phải điểm đã cộng.',
  `pricing_snapshot` JSON NOT NULL COMMENT 'Quy tắc tính giá, phí giao, tỷ lệ điểm và phân bổ giảm giá lúc đặt.',
  `customer_note` VARCHAR(1000) NULL COMMENT 'Ghi chú của khách.',
  `internal_note` TEXT NULL COMMENT 'Ghi chú nội bộ, không trả về API khách.',
  `prescription_path` VARCHAR(500) NULL COMMENT 'Khóa file đơn thuốc; tải qua phân quyền, không public URL.',
  `expires_at` DATETIME NULL COMMENT 'Hạn thanh toán/giữ tài nguyên.',
  `completed_at` DATETIME NULL COMMENT 'Ngày hoàn tất, mốc báo cáo theo chính sách cần duyệt.',
  `cancelled_at` DATETIME NULL COMMENT 'Ngày hủy/từ chối.',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo, giờ Việt Nam.',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật gần nhất.',
  PRIMARY KEY (id),
  UNIQUE KEY uq_shop_code (order_code),
  UNIQUE KEY uq_shop_checkout (checkout_key),
  UNIQUE KEY uq_shop_legacy (legacy_booking_id),
  KEY ix_shop_user (user_id,created_at,id),
  KEY ix_shop_status (status,created_at,id),
  KEY ix_shop_payment (payment_status,created_at,id),
  KEY ix_shop_method (payment_method,created_at,id),
  KEY ix_shop_created (created_at,id),
  KEY ix_shop_completed (completed_at,id),
  KEY ix_shop_expiry (status,expires_at),
  KEY ix_shop_phone (recipient_phone,created_at),
  CONSTRAINT ck_shop_orders CHECK (subtotal>=0 AND shipping_fee>=0 AND voucher_discount>=0 AND points_discount>=0 AND total_amount=subtotal+shipping_fee-voucher_discount-points_discount AND total_amount>=0 AND paid_amount>=0 AND refunded_amount>=0 AND refunded_amount<=paid_amount)
